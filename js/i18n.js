  const LANGS = ["es", "eu"];
  let currentLang = (App.Storage && App.Storage.getSettings().lang) || "es";
  if (!LANGS.includes(currentLang)) currentLang = "es";

  function t(key) {
    const entry = DICT[currentLang] && DICT[currentLang][key];
    if (entry !== undefined) return entry;
    return (DICT.es && DICT.es[key]) || key;
  }

  function applyStaticDom(root) {
    const scope = root || document;
    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    scope.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria-label")));
    });
    scope.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
    });
  }

  const I18n = {
    LANGS,
    getLang() { return currentLang; },
    setLang(lang) {
      if (!LANGS.includes(lang)) return;
      currentLang = lang;
      document.documentElement.setAttribute("lang", lang === "eu" ? "eu" : "es");
      if (App.Storage) App.Storage.setSetting("lang", lang);
      applyStaticDom();
      document.dispatchEvent(new CustomEvent("app:langchange", { detail: { lang } }));
    },
    t,
    applyStaticDom,
  };

  App.I18n = I18n;
